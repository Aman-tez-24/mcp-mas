"""
Shared Data Models and State Schemas
Defines structured objects for Evidence, Claims, Tasks, RunState, and Evaluation.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ClaimStatus(str, Enum):
    SUPPORTED = "SUPPORTED"
    PARTIALLY_SUPPORTED = "PARTIALLY_SUPPORTED"
    UNSUPPORTED = "UNSUPPORTED"
    CONTRADICTED = "CONTRADICTED"


class ResearchTask(BaseModel):
    id: str = Field(..., description="Unique subtask ID, e.g. T1, T2")
    task: str = Field(..., description="Specific verifiable research query")
    status: str = Field(default="pending", description="Status: pending, completed, failed")


class Evidence(BaseModel):
    evidence_id: str = Field(..., description="Stable evidence identifier, e.g. E1, E2")
    document_id: str = Field(default="UNKNOWN", description="Document identifier, e.g. DOC-001")
    source: str = Field(..., description="Source citation or document title")
    text: str = Field(..., description="Retrieved excerpt or passage text")
    relevance: float = Field(default=1.0, ge=0.0, le=1.0, description="Relevance score (0-1)")
    source_quality: float = Field(default=0.9, ge=0.0, le=1.0, description="Source credibility rating")


class Claim(BaseModel):
    claim_id: str = Field(..., description="Unique claim identifier, e.g. C1, C2")
    statement: str = Field(..., description="Factual proposition asserted by the system")
    evidence_ids: List[str] = Field(default_factory=list, description="Associated evidence IDs (e.g. ['E1'])")
    supported: bool = Field(default=True, description="Whether claim is verified by evidence")
    status: ClaimStatus = Field(default=ClaimStatus.SUPPORTED, description="Verification classification")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Verification confidence score")
    contradiction_notes: Optional[str] = Field(default=None, description="Notes if conflicting evidence was detected")


class AgentStepLog(BaseModel):
    name: str = Field(..., description="Agent name: planner, researcher, verifier, writer, evaluator")
    latency_ms: float = Field(default=0.0, description="Execution duration in milliseconds")
    tokens: Dict[str, int] = Field(default_factory=lambda: {"input": 0, "output": 0})
    status: str = Field(default="success")
    summary: str = Field(default="")


class MCPCallLog(BaseModel):
    tool: str = Field(..., description="Name of MCP tool called")
    arguments: Dict[str, Any] = Field(default_factory=dict)
    success: bool = Field(default=True)
    latency_ms: float = Field(default=0.0)
    error: Optional[str] = None


class RunMetrics(BaseModel):
    latency_ms: float = 0.0
    cost_usd: float = 0.0
    total_tokens: int = 0
    input_tokens: int = 0
    output_tokens: int = 0
    groundedness: float = 1.0
    hallucination_rate: float = 0.0
    citation_correctness: float = 1.0
    evidence_coverage: float = 1.0
    tool_success_rate: float = 1.0
    tool_calls: int = 0


class RunState(BaseModel):
    run_id: str = Field(..., description="Unique run identifier (e.g. 2026-10-22-001)")
    timestamp: str = Field(..., description="ISO 8601 execution timestamp")
    question: str = Field(..., description="User's original research question")
    plan: List[str] = Field(default_factory=list, description="Subtasks generated by planner")
    evidence: List[Evidence] = Field(default_factory=list, description="Retrieved evidence records")
    claims: List[Claim] = Field(default_factory=list, description="Extracted and verified claims")
    final_answer: str = Field(default="", description="Structured synthesis report")
    tool_calls: int = Field(default=0, description="Total count of MCP tool invocations")
    latency_ms: float = Field(default=0.0, description="End-to-end elapsed time in ms")
    input_tokens: int = Field(default=0, description="Total prompt tokens processed")
    output_tokens: int = Field(default=0, description="Total completion tokens generated")
    estimated_cost_usd: float = Field(default=0.0, description="Calculated API cost (USD)")
    hallucination_rate: float = Field(default=0.0, description="Rate of unsupported factual claims")
    groundedness: float = Field(default=1.0, description="Proportion of supported claims over total claims")
    citation_correctness: float = Field(default=1.0, description="Proportion of citations linking to valid evidence")
    evidence_coverage: float = Field(default=1.0, description="Supported factual claims / total factual claims")
    agents: List[AgentStepLog] = Field(default_factory=list, description="Per-agent performance breakdown")
    mcp_calls: List[MCPCallLog] = Field(default_factory=list, description="Audit log of MCP tool calls")
    has_conflict: bool = Field(default=False, description="Whether conflicting evidence was identified")
    conflict_details: Optional[str] = None
    is_baseline: bool = Field(default=False, description="True if run is single-agent baseline")
    llm_mode: str = Field(default="deterministic", description="Engine used: ollama or deterministic")
    model_name: str = Field(default="llama3:latest", description="Model name evaluated")


class QueryRequest(BaseModel):
    question: str = Field(..., min_length=2, description="Research question to investigate")
    max_subtasks: int = Field(default=4, ge=1, le=10, description="Max subtasks for planner")
    use_baseline: bool = Field(default=False, description="If True, execute single-agent baseline instead")


class QueryResponse(BaseModel):
    run_id: str
    question: str
    answer: str
    claims: List[Claim]
    evidence: List[Evidence]
    metrics: RunMetrics
    agents: List[AgentStepLog]
    llm_mode: str
    model_name: str
